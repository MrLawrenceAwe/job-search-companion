import { readFile, writeFile } from "node:fs/promises";

// Unique entry paths let Chrome share contracts without deduplicating scripts
// across execution worlds and content-script declarations.
const entries = {
  "indeed-description-capture.bundle.js": [
    "contracts/job-urls.js", "contracts/messages.js", "blockers/indeed-description-capture.js",
  ],
  "suggestion-card.bundle.js": [
    "contracts/messages.js", "contracts/recommendations.js", "contracts/cv-fit-submissions.js",
    "contracts/cv-fit-settings.js", "cv-fit-client.js", "suggestion-card.js",
  ],
};
const buildEntry = async (entry, sources) => {
  const contents = await Promise.all(sources.map((path) =>
    readFile(new URL(`../extension/${path}`, import.meta.url), "utf8")));
  await writeFile(new URL(`../extension/${entry}`, import.meta.url),
    "// Generated by npm run build. Edit the source files instead.\n" + contents.join("\n"));
};
for (const [entry, sources] of Object.entries(entries)) await buildEntry(entry, sources);
